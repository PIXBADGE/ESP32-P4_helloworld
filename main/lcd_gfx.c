void gfx_fill_rect(esp_lcd_panel_handle_t panel, int x, int y, int w, int h, uint16_t color)
{
    if (w <= 0 || h <= 0) {
        return;
    }
    /* 逐行写入，避免一次性申请大块内存 */
    uint16_t line[256];
    for (int i = 0; i < 256; i++) {
        line[i] = color;
    }
    int x_end = x + w;
    int y_end = y + h;
    for (int row = y; row < y_end; row++) {
        int remain = w;
        int cx = x;
        while (remain > 0) {
            int chunk = remain > 256 ? 256 : remain;
            esp_lcd_panel_draw_bitmap(panel, cx, row, cx + chunk, row + 1, line);
            cx += chunk;
            remain -= chunk;
        }
    }
}

void gfx_fill_screen(esp_lcd_panel_handle_t panel, int w, int h, uint16_t color)
{
    gfx_fill_rect(panel, 0, 0, w, h, color);
}

void gfx_draw_color_bars(esp_lcd_panel_handle_t panel, int w, int h)
{
    const uint16_t bars[] = {
        GFX_WHITE, GFX_YELLOW, GFX_CYAN, GFX_GREEN,
        GFX_MAGENTA, GFX_RED, GFX_BLUE, GFX_BLACK
    };
    int n = sizeof(bars) / sizeof(bars[0]);
    int bar_w = (w + n - 1) / n;
    for (int i = 0; i < n; i++) {
        int x = i * bar_w;
        int bw = (x + bar_w > w) ? (w - x) : bar_w;
        gfx_fill_rect(panel, x, 0, bw, h, bars[i]);
    }
}

void gfx_draw_char(esp_lcd_panel_handle_t panel, int x, int y, char c,
                   uint16_t fg, uint16_t bg, int scale)
{
    if (c < 0x20 || c > 0x7E || scale < 1) {
        c = '?';
    }
    const uint8_t *glyph = s_font5x7[(uint8_t)c - 0x20];
    for (int row = 0; row < 7; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 5; col++) {
            uint16_t color = (bits & (0x10 >> col)) ? fg : bg;
            gfx_fill_rect(panel, x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}

void gfx_draw_string(esp_lcd_panel_handle_t panel, int x, int y, const char *str,
                     uint16_t fg, uint16_t bg, int scale)
{
    int cx = x;
    int char_w = 6 * scale; /* 5 列 + 1 列间距 */
    while (*str) {
        gfx_draw_char(panel, cx, y, *str, fg, bg, scale);
        cx += char_w;
        str++;
    }
}
